//! Claim Provenance Discipline (`AGENTS.md` §II.C) and Personal Knowledge Management
//! Provenance Auditing (`ClaimProvenanceClass`, `EpistemicPkmProvenanceAudit`).

/// Claim Provenance Class (`AGENTS.md` §II.C) enforced across Personal Knowledge Management (PKM)
/// and institutional document ingestion pipelines.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ClaimProvenanceClass {
    /// Computed by the repository code on a real dataset in `data/*.csv` sealed in `data/SHA256SUMS`.
    Measured,
    /// Output of a seeded generative model (`SplitMix64`).
    Simulated,
    /// Hand-set design target or operating point assumption.
    Assumed,
    /// Constant transcribed from external literature (informative only, never a gate boolean).
    LiteratureInformative,
    /// Unanchored summary or synthetic note generated by an LLM without primary dataset verification.
    UnanchoredLlmSynthesis,
}

/// Executable Personal Knowledge Management (PKM) Provenance Audit (`EpistemicPkmProvenanceAudit`),
/// preventing secondary LLM summaries or assumed targets from being laundered into `Measured` claims.
#[derive(Debug, Clone, PartialEq)]
pub struct EpistemicPkmProvenanceAudit {
    /// Total claims ingested into the knowledge base.
    pub total_nodes: usize,
    /// Number of nodes where an `Assumed`, `Simulated`, `LiteratureInformative`, or `UnanchoredLlmSynthesis`
    /// source was illegally promoted to `Measured` ("provenance laundering").
    pub provenance_laundering_violations: usize,
    /// Number of comparisons equating `Measured` and `Assumed`/`Simulated` values as equal evidence (Rule 1 violation).
    pub cross_class_equating_violations: usize,
    /// True if every `Measured` node is anchored to a verified dataset SHA-256 and zero provenance laundering occurred.
    pub pkm_provenance_clean: bool,
}

impl EpistemicPkmProvenanceAudit {
    /// Audits a sequence of `(source_origin_class, declared_target_class, has_verified_dataset_sha256)` transitions
    /// and a count of forbidden cross-class comparisons (`Measured` vs. `Assumed`/`Simulated` treated as equal evidence).
    pub fn audit_ingestion(
        transitions: &[(ClaimProvenanceClass, ClaimProvenanceClass, bool)],
        cross_class_equating_violations: usize,
    ) -> Self {
        let mut laundering = 0usize;
        for &(origin, declared, has_sha) in transitions {
            if declared == ClaimProvenanceClass::Measured
                && (origin != ClaimProvenanceClass::Measured || !has_sha)
            {
                laundering += 1;
            }
            if origin == ClaimProvenanceClass::UnanchoredLlmSynthesis
                && declared != ClaimProvenanceClass::UnanchoredLlmSynthesis
            {
                laundering += 1;
            }
        }
        Self {
            total_nodes: transitions.len(),
            provenance_laundering_violations: laundering,
            cross_class_equating_violations,
            pkm_provenance_clean: laundering == 0 && cross_class_equating_violations == 0,
        }
    }
}
