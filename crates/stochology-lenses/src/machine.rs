//! Almost-Perfect Machine `M = (T, Φ, θ)` and First-Class Authentic Model Form (`δ(x) + Ŝ*`).
//!
//! 1. **Almost-Perfect Machine `M = (T, Φ, θ)` (`AlmostPerfectMachine`):**
//!    - `T` (Atomic Feature Encoder): distills measurable atomic features while preserving mutual information
//!      up to DPI gap $\Delta_{\mathrm{DPI}} = I(W; X) - I(W; T(X)) \le \delta$, audited via [`DpiMarkovChain`] and [`SdpiHierarchy`].
//!    - `Φ` (Compositional Nonlinearity Layer): composes nonlinear primitives with Barron spectral rate
//!      $\mathbb{E}\|f - f_W\|_2^2 \le C_f^2 / W$ and Telgarsky depth-$D$ exponential region multiplication ($2^D$ linear regions with $2D$ parameters).
//!    - `θ` (Readout Decoder & Basis Completeness): solves the linear readout over the atomic basis and audits
//!      Gram effective dimension $d_{\mathrm{eff}} = \frac{(\mathrm{tr}\,G)^2}{\|G\|_F^2}$, off-diagonal coherence, and Fano/minimax optimality (`P1`–`P5`).
//! 2. **First-Class Authentic Model Form (`AuthenticModelForm`):**
//!    - Represents the model not by a lone mean or point prediction, but by the surviving invariant core $\hat{S}^*$,
//!      the anchored Kennedy-O'Hagan structural discrepancy $\delta(x) \sim \mathcal{GP}(0, k_{\text{anchored}})$,
//!      explicitly named discarded spurious atoms (`DiscardedAtomRecord`), simultaneous closure of the 6 numerical
