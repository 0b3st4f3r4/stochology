/// Audit of the 5 formal properties (`P1`–`P5`) required for an $(\varepsilon, \delta)$-Almost-Perfect Machine `M = (T, Φ, θ)`.
#[derive(Debug, Clone, PartialEq)]
pub struct AlmostPerfectMachine {
    pub seed: u64,
    pub width_w: usize,
    pub depth_d: usize,
    /// Barron spectral norm $C_f = \sum_k |\alpha_k| |\omega_k|$ of target nonlinear function $f$.
    pub barron_norm_c_f: f64,
    /// Empirical supremum approximation error $\sup_{x \in K} |M(x) - f(x)|$.
    pub sup_error_epsilon: f64,
    /// Empirical $L_2^2$ approximation error $\frac{1}{n}\sum_{i=1}^n (M(x_i) - f(x_i))^2$.
    pub empirical_l2_sq: f64,
    /// Theoretical Barron rate upper bound $C_f^2 / W$.
    pub barron_rate_bound: f64,
    /// Information loss $\Delta_{\mathrm{DPI}} = I(W; X) - I(W; T(X))$ in nats across encoder $T$.
    pub dpi_gap_delta_nats: f64,
    /// Strong Data Processing Inequality contraction constants $(\eta_{\chi^2}, \eta_{\mathrm{KL}}, \eta_{\mathrm{TV}})$ of $T$.
    pub sdpi_contraction_triple: (f64, f64, f64),
    /// Irreducible Fano classification error floor $P_e^{\min}$ vs. empirical minimax risk ratio.
    pub fano_error_floor: f64,
    /// Ratio of empirical excess MSE to minimax floor $\sigma^2 W / n$.
    pub minimax_rate_ratio: f64,
    /// Number of affine linear regions generated by depth-$D$ composition ($2^D$) vs. parameter count ($2D$).
    pub composed_linear_regions: usize,
    pub region_to_parameter_ratio: f64,
    /// Effective spectral dimension $d_{\mathrm{eff}} = \frac{(\mathrm{tr}\,G)^2}{\|G\|_F^2}$ of the $W$-atom Gram matrix $G$.
    pub atomic_effective_dimension: f64,
    /// Maximum off-diagonal coherence $\max_{j \neq k} |G_{jk}|$ between distinct normalized basis atoms.
    pub max_off_diagonal_coherence: f64,
    /// `P1`: Universal density ($\sup_x |M(x) - f(x)| \le \varepsilon$ and $L_2^2 \le C_f^2 / W$).
    pub p1_universal_density: bool,
    /// `P2`: Informational $\delta$-sufficiency ($\Delta_{\mathrm{DPI}} \le \delta$ and valid SDPI hierarchy).
    pub p2_informational_sufficiency: bool,
    /// `P3`: Fano/minimax rate optimality ($0.25 \le \text{MSE} / \text{minimax\_floor} \le 2.5$ and $P_e^{\min} > 0$).
    pub p3_fano_minimax_optimality: bool,
    /// `P4`: Compositional depth efficiency ($\text{regions} = 2^D$ and $2^D / (2D) \ge 4.0$, exponential regions per parameter).
    pub p4_compositional_efficiency: bool,
    /// `P5`: Atomic completeness ($d_{\mathrm{eff}} \ge 0.80 W$ and off-diagonal coherence $< 0.15$).
    pub p5_atomic_completeness: bool,
    /// True if and only if all five properties `P1`–`P5` hold simultaneously.
    pub all_p1_to_p5_approved: bool,
}

impl AlmostPerfectMachine {
    /// Evaluates the canonical $(\varepsilon, \delta)$-Almost-Perfect Machine `M = (T, Φ, θ)` with `seed = 2026`.
    pub fn evaluate_canonical(seed: u64) -> Self {
        Self::evaluate_with_config(seed, 0.015, 8, 6, 0.12, 0.05)
    }

    /// Evaluates `M = (T, Φ, θ)` under explicit architectural parameters:
    /// - `encoder_noise_q`: channel crossover in $X \to T(X)$ governing $\Delta_{\mathrm{DPI}}$,
    /// - `width_w`: number of spectral Fourier-Barron atoms in decoder $\theta$,
    /// - `depth_d`: compositional depth of $\Phi$ (sawtooth / ReLU folding layers),
    /// - `epsilon_tol`: maximum tolerated $\sup_x |M(x) - f(x)|$,
    /// - `delta_dpi_tol`: maximum tolerated DPI sufficiency gap $\Delta_{\mathrm{DPI}}$.
    pub fn evaluate_with_config(
        seed: u64,
        encoder_noise_q: f64,
        width_w: usize,
        depth_d: usize,
        epsilon_tol: f64,
        delta_dpi_tol: f64,
    ) -> Self {
        let w_atoms = width_w.max(1);
        let d_layers = depth_d.max(1);
        let mut rng = Rng::new(seed);

        // 1. Target nonlinear function in Barron spectral class on [-pi, pi]:
        // f(x) = sum_{k=1..4} alpha_k * cos(k * x) + beta_k * sin(k * x)
        let target_modes: [(f64, f64, f64); 4] = [
            (1.0, 0.90, -0.40),
            (2.0, -0.55, 0.35),
            (3.0, 0.30, -0.20),
            (4.0, -0.15, 0.10),
        ];
        let barron_c_f: f64 = target_modes
            .iter()
            .map(|&(freq, a, b)| freq * (a.abs() + b.abs()))
            .sum();

        let n_grid = 240usize;
        let sigma_noise = 0.04;
        let mut x_grid = Vec::with_capacity(n_grid);
        let mut f_true = Vec::with_capacity(n_grid);
        let mut y_noisy = Vec::with_capacity(n_grid);

        for i in 0..n_grid {
            let u = -std::f64::consts::PI
                + 2.0 * std::f64::consts::PI * ((i as f64) + 0.5) / (n_grid as f64);
            let mut fx = 0.0;
            for &(freq, a, b) in &target_modes {
                fx += a * (freq * u).cos() + b * (freq * u).sin();
            }
            x_grid.push(u);
            f_true.push(fx);
            y_noisy.push(fx + rng.normal(0.0, sigma_noise));
        }

        // Build W-atom orthonormal trigonometric basis T(x) -> Phi(T(x)) on [-pi, pi]
        // Pairs of (sqrt(2)*cos(k*x), sqrt(2)*sin(k*x)) for k = 1, 2, ...
        let eval_atom = |atom_idx: usize, x: f64| -> f64 {
            let k = ((atom_idx / 2) + 1) as f64;
            let s = std::f64::consts::SQRT_2;
            if atom_idx.is_multiple_of(2) {
                s * (k * x).cos()
            } else {
                s * (k * x).sin()
            }
        };

        // Gram matrix G_{jk} = (1/n) sum_i phi_j(x_i) phi_k(x_i) and projection decoder theta_j = (1/n) sum_i y_i phi_j(x_i)
        let n_f = n_grid as f64;
        let mut gram = vec![vec![0.0; w_atoms]; w_atoms];
        let mut theta = vec![0.0; w_atoms];
        #[allow(clippy::needless_range_loop)]
        for j in 0..w_atoms {
            let mut sum_y_phi = 0.0;
            for i in 0..n_grid {
                let pj = eval_atom(j, x_grid[i]);
                sum_y_phi += y_noisy[i] * pj;
                for k in j..w_atoms {
                    let pk = eval_atom(k, x_grid[i]);
                    gram[j][k] += pj * pk / n_f;
                }
            }
            theta[j] = sum_y_phi / n_f;
            for k in 0..j {
                gram[j][k] = gram[k][j];
            }
        }

        // Evaluate M(x) = sum_{j=0..W-1} theta_j phi_j(x) against true f(x)
        let mut sup_err = 0.0_f64;
        let mut l2_sq_sum = 0.0_f64;
        for i in 0..n_grid {
            let mut pred = 0.0;
            for (j, &th) in theta.iter().enumerate() {
                pred += th * eval_atom(j, x_grid[i]);
            }
            let err = (pred - f_true[i]).abs();
            sup_err = sup_err.max(err);
            l2_sq_sum += err * err;
        }
        let emp_l2_sq = l2_sq_sum / n_f;
        let barron_bound = (barron_c_f * barron_c_f) / (w_atoms as f64);

        // Gram effective dimension d_eff = (tr G)^2 / ||G||_F^2 and max off-diagonal coherence
        let mut tr_g = 0.0;
        let mut frob_sq = 0.0;
        let mut max_coh = 0.0_f64;
        for (j, row) in gram.iter().enumerate() {
            tr_g += row[j];
            for (k, &g_jk) in row.iter().enumerate() {
                frob_sq += g_jk * g_jk;
                if j != k {
                    max_coh = max_coh.max(g_jk.abs());
                }
            }
        }
        let d_eff = (tr_g * tr_g) / frob_sq.max(1e-15);

        // 2. Informational sufficiency of T: Markov chain W -> X -> T(X) -> Z
        let q = encoder_noise_q.clamp(0.0001, 0.4999);
        let w_to_x = vec![vec![0.92, 0.08], vec![0.08, 0.92]];
        let x_to_tx = vec![vec![1.0 - q, q], vec![q, 1.0 - q]];
        let tx_to_z = vec![vec![0.95, 0.05], vec![0.05, 0.95]];
        let dpi = DpiMarkovChain::compute(&[0.5, 0.5], &w_to_x, &x_to_tx, &tx_to_z);
        let dpi_gap = (dpi.i_w_x_nats - dpi.i_w_y_nats).max(0.0);
        let sdpi = SdpiHierarchy::compute(&[0.5, 0.5], &x_to_tx);

        // 3. Fano error floor and minimax estimation rate sigma^2 * W / n
        let fano_pe = fano_error_floor(2, (2.0_f64).ln(), dpi.i_w_y_nats);
        let minimax_floor = (sigma_noise * sigma_noise * (w_atoms as f64)) / n_f;
        // Total prediction risk E[(M(X) - f(X))^2] compared to minimax floor when W >= 8 covers all 4 modes
        let minimax_ratio = emp_l2_sq / minimax_floor.max(1e-12);

        // 4. Compositional efficiency (Telgarsky depth-D sawtooth f_D(x) = f_1(f_{D-1}(x)) with f_1(u) = ReLU(2u) - ReLU(4u - 2)):
        // Count exact sign-changes of derivative df_D/dx across [0, 1] to verify 2^D affine linear regions with 2*D parameters
        let sawtooth_1 = |u: f64| -> f64 {
            let r1 = (2.0 * u).max(0.0);
            let r2 = (4.0 * u - 2.0).max(0.0);
            (r1 - r2).max(0.0)
        };
        let n_probe = (1usize << (d_layers + 2)).max(64);
        let mut prev_slope_sign = 0i32;
        let mut linear_regions = 0usize;
        for m in 0..n_probe {
            let x0 = (m as f64 + 0.25) / (n_probe as f64);
            let x1 = (m as f64 + 0.75) / (n_probe as f64);
            let mut y0 = x0;
            let mut y1 = x1;
            for _ in 0..d_layers {
                y0 = sawtooth_1(y0);
                y1 = sawtooth_1(y1);
            }
            let sign = if y1 > y0 { 1 } else { -1 };
            if sign != prev_slope_sign {
                linear_regions += 1;
                prev_slope_sign = sign;
            }
        }
        let param_count = (2 * d_layers).max(1) as f64;
        let reg_per_param = (linear_regions as f64) / param_count;

        let p1 = sup_err <= epsilon_tol && emp_l2_sq <= barron_bound;
        let p2 = dpi.dpi_satisfied && dpi_gap <= delta_dpi_tol && sdpi.hierarchy_valid;
        let p3 = fano_pe > 0.0 && (0.25..=2.5).contains(&minimax_ratio);
        let p4 = linear_regions == (1usize << d_layers) && reg_per_param >= 4.0;
        let p5 = d_eff >= 0.80 * (w_atoms as f64) && max_coh < 0.15;

        Self {
            seed,
            width_w: w_atoms,
            depth_d: d_layers,
            barron_norm_c_f: barron_c_f,
            sup_error_epsilon: sup_err,
            empirical_l2_sq: emp_l2_sq,
            barron_rate_bound: barron_bound,
            dpi_gap_delta_nats: dpi_gap,
            sdpi_contraction_triple: (sdpi.eta_chi2, sdpi.eta_kl, sdpi.eta_tv),
            fano_error_floor: fano_pe,
            minimax_rate_ratio: minimax_ratio,
            composed_linear_regions: linear_regions,
            region_to_parameter_ratio: reg_per_param,
            atomic_effective_dimension: d_eff,
            max_off_diagonal_coherence: max_coh,
            p1_universal_density: p1,
            p2_informational_sufficiency: p2,
            p3_fano_minimax_optimality: p3,
            p4_compositional_efficiency: p4,
            p5_atomic_completeness: p5,
            all_p1_to_p5_approved: p1 && p2 && p3 && p4 && p5,
        }
    }
}

